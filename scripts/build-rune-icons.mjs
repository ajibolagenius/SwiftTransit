// Generates assets/rune-glass.generated.ts from the `runeicons` package (devDependency).
// Glass markup uses <mask>/<filter> primitives react-native-svg cannot render; we strip
// them at build time and keep the linearGradients that carry the glass look.
// Run: node scripts/build-rune-icons.mjs
import { writeFileSync } from 'node:fs';
import { getIconById } from 'runeicons';

// lucide name -> runeicons store id + style. Glass where the store has it (closest variant
