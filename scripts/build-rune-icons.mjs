function normalize(variant) {
  const body = variant.markup
    // drop filter definitions (glow) and references - react-native-svg has no SVG filters
    .replace(/<filter\b[^>]*>[\s\S]*?<\/filter>/g, '')
    .replace(/<filter\b[^>]*\/>/g, '')
    .replace(/\sfilter="url\([^"]*\)"/g, '')
    // runeicons glass masks are opaque-shape alpha clips; react-native-svg understands
    // clipPath but not <mask style="mask-type:alpha">, so translate them
    .replace(/<mask\b[^>]*?(?:style="[^"]*")?[^>]*?id="([^"]+)"[^>]*?>/g, '<clipPath id="$1">')
    .replace(/<\/mask>/g, '</clipPath>')
    .replace(/\smask="url\(([^)]*)\)"/g, ' clipPath="url($1)"')
    // unwrap groups left with only the filter removal
    .replace(/<g>\s*<\/g>/g, '')
    // DESIGN.md icon rule: 1.5 stroke for the stroke-style fallbacks
    .replace(/stroke-width="2"/g, 'stroke-width="1.5"')
    .trim();
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${variant.viewBox}">${body}</svg>`;
}

const entries = [];
for (const [key, id, style] of MAPPING) {
  const icon = getIconById(id);
  const variant = icon?.variants?.[style];
  if (!variant) {
    console.error(`FAIL: ${id} has no "${style}" variant (key ${key})`);
    process.exit(1);
  }
  entries.push({ key, id, style, viewBox: variant.viewBox, xml: normalize(variant) });
}

const body = entries
  .map(
    (e) =>
      `  ${e.key}: {\n    id: '${e.id}',\n    style: '${e.style}',\n    viewBox: '${e.viewBox}',\n    xml: ${JSON.stringify(e.xml)},\n  },`,
  )
  .join('\n');

writeFileSync(
  'assets/rune-glass.generated.ts',
  `// GENERATED by scripts/build-rune-icons.mjs from the runeicons package - do not edit by hand.
export type RuneIconEntry = { id: string; style: 'glass' | 'normal'; viewBox: string; xml: string };

export const RUNE_ICONS = {
${body}
} satisfies Record<string, RuneIconEntry>;

export type IconName = keyof typeof RUNE_ICONS;
`,
);
console.log(`wrote assets/rune-glass.generated.ts (${entries.length} icons)`);
